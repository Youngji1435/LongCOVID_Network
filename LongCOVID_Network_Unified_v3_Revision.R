# -- Network plot helper ----------------------------------------------
plot_two_group_network <- function(g_left, g_right,
                                   left_title = "A. Uninfected",
                                   right_title = "B. Infected",
                                   file = NULL,
                                   width = 14, height = 6.5, res = 300,
                                   seed = 123) {
  set.seed(seed)
  
  # make sure both graphs contain all symptom nodes
  all_nodes <- union(V(g_left)$name, V(g_right)$name)
  
  add_missing_vertices <- function(g, all_nodes) {
    missing_nodes <- setdiff(all_nodes, V(g)$name)
    if (length(missing_nodes) > 0) {
      g <- add_vertices(g, nv = length(missing_nodes), name = missing_nodes)
    }
    g
  }
  
  g_left  <- add_missing_vertices(g_left,  all_nodes)
  g_right <- add_missing_vertices(g_right, all_nodes)
  
  # reorder vertices identically
  g_left  <- permute(g_left,  match(all_nodes, V(g_left)$name))
  g_right <- permute(g_right, match(all_nodes, V(g_right)$name))
  
  # use a common layout based on combined graph for comparability
  g_comb <- igraph::union(g_left, g_right, byname = TRUE)
  lay <- layout_with_fr(g_comb, weights = E(g_comb)$weight)
  
  # common community colors
  get_membership <- function(g) {
    if (ecount(g) == 0) return(rep(1L, vcount(g)))
    membership(cluster_louvain(g, weights = E(g)$weight))
  }

  mem_left  <- get_membership(g_left)
  mem_right <- get_membership(g_right)

  # consistent palette across panels
  all_comms <- sort(unique(c(mem_left, mem_right)))
  pal <- setNames(
    grDevices::hcl.colors(length(all_comms), palette = "Dark 3"),
    all_comms
  )

  # node sizes based on strength
  get_vertex_size <- function(g, min_size = 4, max_size = 18) {
    if (ecount(g) == 0) return(rep(min_size, vcount(g)))
    s <- strength(g, weights = E(g)$weight)
    if (max(s, na.rm = TRUE) == min(s, na.rm = TRUE)) {
      return(rep((min_size + max_size) / 2, length(s)))
    }
    scales::rescale(s, to = c(min_size, max_size))
  }
  
  # edge widths based on weight
  get_edge_width <- function(g, min_w = 0.4, max_w = 4) {
    if (ecount(g) == 0) return(numeric(0))
    w <- E(g)$weight
    if (max(w, na.rm = TRUE) == min(w, na.rm = TRUE)) {
      return(rep((min_w + max_w) / 2, length(w)))
    }
    scales::rescale(w, to = c(min_w, max_w))
  }
  
  vsize_left  <- get_vertex_size(g_left)
  vsize_right <- get_vertex_size(g_right)
  ewidth_left  <- get_edge_width(g_left)
  ewidth_right <- get_edge_width(g_right)
  
  vcol_left  <- pal[as.character(mem_left)]
  vcol_right <- pal[as.character(mem_right)]

  # Draw a single panel (used twice: left + right). Legends are placed
  # INSIDE the panel (positive insets, xpd = FALSE) so they cannot spill
  # into the neighbouring panel.
  draw_one_panel <- function(g, mem, vsize, ewidth, vcol, ttl,
                             include_strength_legend = TRUE,
                             include_weight_legend   = TRUE,
                             include_community_legend = TRUE) {
    plot(
      g,
      layout = lay,
      vertex.label        = clean_symptom_names(V(g)$name),
      vertex.label.cex    = 0.8,                # smaller -> avoids overlap
      vertex.label.family = "sans",
      vertex.label.color  = "black",
      vertex.label.font   = 2,
      vertex.size         = vsize,
      vertex.color        = vcol,
      vertex.frame.color  = NA,
      edge.width          = ewidth,
      edge.color          = grDevices::adjustcolor("grey40", alpha.f = 0.35),
      main                = ttl
    )

    if (igraph::ecount(g) > 0 && include_strength_legend) {
      s <- igraph::strength(g, weights = igraph::E(g)$weight)
      s_breaks <- unique(round(pretty(range(s), n = 4)))
      s_breaks <- s_breaks[s_breaks > 0]
      if (length(s_breaks) > 0) {
        legend("topright",
               legend = s_breaks, pch = 16,
               pt.cex = scales::rescale(s_breaks, to = c(1.0, 2.6)),  # narrower so 3000/4000 read evenly
               bty = "n", title = "strength",
               inset    = c(0.02, 0.02),
               cex      = 1.0,
               y.intersp = 1.6)                  # generous, even row spacing
      }
    }

    if (igraph::ecount(g) > 0 && include_weight_legend) {
      w <- igraph::E(g)$weight
      w_breaks <- unique(round(pretty(range(w), n = 4)))
      w_breaks <- w_breaks[w_breaks > 0]
      if (length(w_breaks) > 0) {
        legend("bottomright",
               legend = w_breaks,
               lwd    = scales::rescale(w_breaks, to = c(0.6, 3.5)),
               col    = "grey50",
               bty    = "n", title = "weight",
               inset    = c(0.02, 0.02),
               cex      = 1.0,
               y.intersp = 1.4)
      }
    }

    if (include_community_legend) {
      legend("bottomleft",
             legend = paste("community", sort(unique(mem))),
             pch    = 16,
             col    = pal[as.character(sort(unique(mem)))],
             bty    = "n",
             inset    = c(0.02, 0.02),
             cex      = 1.0,
             y.intersp = 1.3)
    }
  }

  draw_two_group <- function() {
    op <- par(no.readonly = TRUE); on.exit(par(op), add = TRUE)
    par(mfrow = c(1, 2), mar = c(1, 1, 3, 1),
        xpd = FALSE,                  # keep legends inside their own panel
        cex.main = 1.6)
    draw_one_panel(g_left,  mem_left,  vsize_left,  ewidth_left,  vcol_left,  left_title)
    draw_one_panel(g_right, mem_right, vsize_right, ewidth_right, vcol_right, right_title)
    invisible(NULL)
  }

  # Save to PNG (clean device, no overlap with previous calls).
  if (!is.null(file)) {
    png(file, width = width, height = height, units = "in", res = res)
    draw_two_group()
    dev.off()
    message("Saved network plot to: ", file)
    if (interactive()) try(utils::browseURL(file), silent = TRUE)
  } else {
    # No file requested: render to the current device only.
    draw_two_group()
  }

  invisible(NULL)
}

