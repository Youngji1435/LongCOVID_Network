  # -- Time-sliced network builder ------------------------------------
  build_symptom_network_timeslice <- function(df_sub, id_col, symptom_cols,
                                              timebin_col = "timebin") {
    df_sub <- df_sub %>%
      filter(!is.na(.data[[timebin_col]])) %>%
      mutate(unit_id = paste0(.data[[id_col]], "_", .data[[timebin_col]]))
    long_sym <- df_sub %>%
      pivot_longer(cols = all_of(symptom_cols), names_to = "symptom", values_to = "value_raw") %>%
      mutate(value = to01(value_raw)) %>%
      filter(value == 1) %>%
      select(unit_id, symptom) %>% distinct()
    if (nrow(long_sym) == 0) {
      return(list(graph = make_empty_graph(), edges = tibble(), long_sym = long_sym, comm = NULL))
    }
    pairs <- long_sym %>%
      inner_join(long_sym, by = "unit_id", suffix = c("_1","_2")) %>%
      filter(symptom_1 < symptom_2) %>%
      transmute(source = symptom_1, target = symptom_2, unit_id)
    edge_raw <- pairs %>%
      group_by(source, target) %>%
      summarise(weight = n_distinct(unit_id), .groups = "drop")
    g <- graph_from_data_frame(edge_raw, directed = FALSE)
    E(g)$weight <- edge_raw$weight
    comm <- cluster_louvain(g, weights = E(g)$weight)
    V(g)$community <- membership(comm)
    V(g)$strength  <- strength(g, weights = E(g)$weight)
    list(graph = g, edges = edge_raw, long_sym = long_sym, comm = comm)
  }

  pagerank_gini_safe <- function(g) {
    if (is.null(g) || ecount(g) == 0) return(NA_real_)
    pr <- page_rank(g, weights = E(g)$weight)$vector
    ineq(pr, type = "Gini")
  }

  modularity_safe <- function(comm_obj) {
    if (is.null(comm_obj)) return(NA_real_)
    modularity(comm_obj)
  }

  # -- Bootstrap CIs for time-bin network metrics -----------------------
  # Unit-level bootstrap: units are person-window symptom profiles
  # (symptom = reported at any visit within the window), and resampled
  # duplicates count individually via matrix-based co-occurrence
  # counting, so intervals are centered on the observed estimates.
  # (An earlier implementation resampled visit rows and collapsed
  # duplicated units under distinct-unit counting, which biased
  # co-occurrence totals downward by approximately 1 - 1/e.)
  bootstrap_timebin_metrics <- function(df2, id_col, symptom_cols,
                                        infect_col = "infected01",
                                        timebin_col = "timebin",
                                        B = 300,
                                        seed = 123) {
    set.seed(seed)
    tb_levels <- c("0-3", "3-6", "6-12", "12-24")

    units_all <- df2 %>%
      dplyr::filter(!is.na(.data[[timebin_col]]),
                    as.character(.data[[timebin_col]]) %in% tb_levels) %>%
      dplyr::select(dplyr::all_of(c(id_col, infect_col, timebin_col,
                                    symptom_cols))) %>%
      dplyr::mutate(dplyr::across(dplyr::all_of(symptom_cols), to01)) %>%
      dplyr::group_by(.data[[id_col]], .data[[infect_col]],
                      .data[[timebin_col]]) %>%
      dplyr::summarise(dplyr::across(dplyr::all_of(symptom_cols), max),
                       .groups = "drop")

    metrics_from_units <- function(X) {
      A <- crossprod(X); diag(A) <- 0
      keep <- rowSums(A) > 0
      A <- A[keep, keep, drop = FALSE]
      if (nrow(A) < 2) {
        return(c(density = NA_real_, modularity = NA_real_,
                 pagerank_gini = NA_real_, assort = NA_real_))
      }
      g <- igraph::graph_from_adjacency_matrix(A, mode = "undirected",
                                               weighted = TRUE, diag = FALSE)
      comm <- igraph::cluster_louvain(g, weights = igraph::E(g)$weight)
      pr <- igraph::page_rank(g, weights = igraph::E(g)$weight)$vector
      c(density = sum(igraph::E(g)$weight) /
          (igraph::vcount(g) * (igraph::vcount(g) - 1) / 2),
        modularity    = igraph::modularity(comm),
        pagerank_gini = ineq::ineq(pr, type = "Gini"),
        assort        = weighted_assortativity_strength(g))
    }

    out <- list(); k <- 1
    for (grp in c(0, 1)) {
      for (tb in tb_levels) {
        U <- units_all %>%
          dplyr::filter(.data[[infect_col]] == grp,
                        as.character(.data[[timebin_col]]) == tb)
        if (nrow(U) < 2) next
        X <- as.matrix(U[, symptom_cols])
        storage.mode(X) <- "integer"
        boot <- replicate(B, metrics_from_units(
          X[sample(nrow(X), nrow(X), replace = TRUE), , drop = FALSE]))
        qs <- apply(boot, 1, stats::quantile, probs = c(0.025, 0.975),
                    na.rm = TRUE)
        out[[k]] <- tibble::tibble(
          infected   = grp,
          timebin    = tb,
          wd_lcl     = qs[1, "density"],       wd_ucl     = qs[2, "density"],
          mod_lcl    = qs[1, "modularity"],    mod_ucl    = qs[2, "modularity"],
          pg_lcl     = qs[1, "pagerank_gini"], pg_ucl     = qs[2, "pagerank_gini"],
          assort_lcl = qs[1, "assort"],        assort_ucl = qs[2, "assort"])
        k <- k + 1
      }
    }
    dplyr::bind_rows(out)
  }
  
  
  
  
  
  
  # -- Loop over groups × timebins ------------------------------------
  timebins <- c("0-3","3-6","6-12","12-24")
  results_metrics <- list()
  results_nodes   <- list()

  for (grp in c(0, 1)) {
    for (tb in timebins) {
      df_sub <- df2 %>% filter(infected01 == grp, as.character(timebin) == tb)
      net    <- build_symptom_network_timeslice(df_sub, id_col, symptom_cols, "timebin")
      g      <- net$graph

      met <- tibble(
        infected               = grp,
        timebin                = tb,
        n_units                = n_distinct(paste0(df_sub[[id_col]], "_", tb)),
        nodes                  = vcount(g),
        edges                  = ecount(g),
        weighted_density       = if (ecount(g) > 0) sum(E(g)$weight) / (vcount(g) * (vcount(g)-1) / 2) else NA_real_,
        modularity             = modularity_safe(net$comm),
        pagerank_gini          = pagerank_gini_safe(g),
        strength_assortativity = if (ecount(g) > 0) weighted_assortativity_strength(g) else NA_real_
      )
      results_metrics[[paste0("g", grp, "_", tb)]] <- met

      if (ecount(g) > 0) {
        pr <- page_rank(g, weights = E(g)$weight)$vector
        st <- strength(g, weights = E(g)$weight)
        results_nodes[[paste0("nodes_g", grp, "_", tb)]] <- tibble(
          infected  = grp, timebin = tb,
          symptom   = names(pr),
          pagerank  = as.numeric(pr),
          strength  = as.numeric(st),
          community = as.integer(V(g)$community)
        )
      }
    }
  }

  metrics_df <- bind_rows(results_metrics) %>%
    mutate(group  = ifelse(infected == 1, "Infected", "Not infected"),
           timebin = factor(timebin, levels = timebins))
  

  
  
  # -- Bootstrap CIs for time-bin metrics -------------------------------
