n_boot_pr <- 300   # set to ~500 for the final paper figure

# -- Bootstrap node-level PageRank by (group, timebin) ---------------
bootstrap_node_pagerank_timebin <- function(df2,
                                            id_col,
                                            symptom_cols,
                                            infect_col  = "infected01",
                                            timebin_col = "timebin",
                                            timebin_levels = c("0-3","3-6","6-12","12-24"),
                                            B = 300,
                                            seed = 123) {
  set.seed(seed)
  out <- list(); k <- 1

  for (grp in c(0, 1)) {
    for (tb in timebin_levels) {

      df_sub <- df2 %>%
        dplyr::filter(.data[[infect_col]] == grp,
                      as.character(.data[[timebin_col]]) == tb)
      n_sub <- nrow(df_sub)
      if (n_sub < 2) next

      for (b in seq_len(B)) {
        samp <- df_sub[sample(seq_len(n_sub), n_sub, replace = TRUE), , drop = FALSE]
        net  <- build_symptom_network_timeslice(samp, id_col, symptom_cols, timebin_col)
        g    <- net$graph
        if (igraph::ecount(g) == 0) next

        pr <- igraph::page_rank(g, weights = igraph::E(g)$weight)$vector
        out[[k]] <- tibble::tibble(
          b        = b,
          infected = grp,
          timebin  = tb,
          symptom  = names(pr),
          pagerank = as.numeric(pr)
        )
        k <- k + 1
      }
    }
    message("  bootstrap done for group ", grp)
  }

  dplyr::bind_rows(out)
}

# -- Pair Δ across matched bootstrap iterations ----------------------
compute_boot_delta <- function(boot_pr) {
  boot_pr %>%
    tidyr::pivot_wider(
      id_cols     = c(b, timebin, symptom),
      names_from  = infected,
      values_from = pagerank,
      names_prefix = "g"
    ) %>%
    dplyr::mutate(delta = g1 - g0) %>%
    dplyr::filter(!is.na(delta))
}

# -- Summarise Δ per (symptom, timebin) ------------------------------
summarise_delta_by_timebin <- function(boot_delta) {
  boot_delta %>%
    dplyr::group_by(symptom, timebin) %>%
    dplyr::summarise(
      delta_mean   = mean(delta, na.rm = TRUE),
      delta_lcl    = stats::quantile(delta, 0.025, na.rm = TRUE),
      delta_ucl    = stats::quantile(delta, 0.975, na.rm = TRUE),
      p_two_sided  = 2 * pmin(mean(delta <= 0, na.rm = TRUE),
                              mean(delta >= 0, na.rm = TRUE)),
      sig          = (stats::quantile(delta, 0.025, na.rm = TRUE) > 0) |
                     (stats::quantile(delta, 0.975, na.rm = TRUE) < 0),
      .groups = "drop"
    )
}

