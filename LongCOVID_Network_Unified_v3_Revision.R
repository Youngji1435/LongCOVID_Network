    dplyr::mutate(timebin = factor(as.character(timebin), levels = timebins))

  # -- Temporal trend plots -------------------------------------------
  p_density <- ggplot(metrics_df, aes(x = timebin, y = weighted_density,
                                       group = group, color = group)) +
    geom_line() + geom_point(size = 2) +
